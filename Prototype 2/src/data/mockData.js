export function formatRp(amount) {
  return 'Rp' + Number(amount || 0).toLocaleString('id-ID')
}

export function calculateVoucherDiscount(voucher, subtotal, serviceType) {
  if (!voucher) return 0
  if (voucher.serviceType !== 'all' && voucher.serviceType !== serviceType) return 0
  if (subtotal < voucher.minSpend) return 0
  if (voucher.discountType === 'percent') {
    return Math.min(Math.round((subtotal * voucher.value) / 100), voucher.maxDiscount)
  }
  return Math.min(voucher.value, subtotal)
}
